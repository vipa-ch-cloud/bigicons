 * Палитры приложения (перенесены из TgAuto): «Цвет 1» (индиго), «Эспрессо», «Цвет 2» (лес).
 * Каждая есть в светлом и тёмном варианте. Контраст пар «on-цвет / фон» проверяется PaletteContrastTest.
 */
object Palettes {
    const val INDIGO = "indigo"
    const val ESPRESSO = "espresso"
    const val FOREST = "forest"

    /** id палитры и её название в интерфейсе. */
    val all: List<Pair<String, String>> = listOf(INDIGO to "Цвет 1", ESPRESSO to "Эспрессо", FOREST to "Цвет 2")

    fun scheme(palette: String, dark: Boolean): ColorScheme = when (palette) {
        ESPRESSO -> if (dark) EspressoDark else EspressoLight
        FOREST -> if (dark) ForestDark else ForestLight
        else -> if (dark) IndigoDark else IndigoLight
    }
}

